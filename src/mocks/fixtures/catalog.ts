function weighted<T>(random: ReturnType<typeof createRandom>, entries: [T, number][]): T {
  const total = entries.reduce((sum, [, weight]) => sum + weight, 0)
  let roll = random.next() * total
  for (const [value, weight] of entries) {
    roll -= weight
    if (roll <= 0) return value
  }
  return entries[entries.length - 1]![0]
}

/** Log-uniform price between 0.02 and 12.30 ETH (the range drawn in the price filter). */
function randomPrice(random: ReturnType<typeof createRandom>) {
  const value = Math.exp(Math.log(0.02) + random.next() * (Math.log(12.3) - Math.log(0.02)))
  const decimals = value < 0.1 ? 3 : 2
  return value.toFixed(decimals)
}

function generatedSeeds(count: number): Seed[] {
  const random = createRandom(2026)
  const usedNames = new Set(FIGMA_SEEDS.map((seed) => seed.name))
  const suffixes = Object.keys(SUFFIX_ART)
  const seeds: Seed[] = []

  while (seeds.length < count) {
    const prefix = random.pick(PREFIXES)
    const suffix = random.pick(suffixes)
    const tokenNumber = random.int(1, 999)
    const name = `${prefix} ${suffix} #${String(tokenNumber).padStart(3, '0')}`
    if (usedNames.has(name)) continue
    usedNames.add(name)

    const index = seeds.length
    const hoursAgo = 8 + index * 9 + random.int(0, 5)
    const soldOut = random.chance(0.06)
    seeds.push({
      id: name.toLowerCase().replace(/#/g, '').replace(/\s+/g, '-'),
      name,
      tokenNumber,
      art: SUFFIX_ART[suffix]!,
      price: randomPrice(random),
      previousPrice: undefined,
      category: weighted(random, CATEGORY_WEIGHTS),
      network: weighted(random, NETWORK_WEIGHTS),
      creator: random.int(0, CREATORS.length - 1),
      trendingScore: random.int(5, 99),
      isNew: hoursAgo <= 14 * 24,
      listedAt: iso(hoursAgo),
      stock: soldOut ? [0, 0, 0] : [random.int(0, 1), random.int(0, 10), random.int(0, 50)],
      open: soldOut ? false : random.chance(0.4),
      reviews: random.int(0, 14),
      collection: random.chance(0.25) ? 'kurio-editions' : undefined,
    })
    if (random.chance(0.12)) {
      const last = seeds[seeds.length - 1]!
      last.previousPrice = eth.bps(last.price, 11_500)
    }
  }
  return seeds
}

function buildEditions(seed: Seed): EditionFixture[] {
  const [one, ten, fifty] = seed.stock
  const editions: EditionFixture[] = [
    {
      id: '1-1',
      label: '1/1',
      supply: 1,
      available: one,
      price: eth.bps(seed.price, 40_000),
      maxPerOrder: 1,
    },
    {
      id: '1-10',
      label: '1/10',
      supply: 10,
      available: ten,
      price: eth.bps(seed.price, 18_000),
      maxPerOrder: 3,
    },
    { id: '1-50', label: '1/50', supply: 50, available: fifty, price: seed.price, maxPerOrder: 10 },
  ]
  if (seed.open) {
    const openPrice = eth.bps(seed.price, 4_000)
    editions.push({
      id: 'open',
      label: 'ABERTA',
      supply: null,
      available: 9_999,
      price: eth.cmp(openPrice, '0.005') < 0 ? '0.005' : openPrice,
      maxPerOrder: 20,
    })
  }
  return editions
}

function buildReviews(seed: Seed, random: ReturnType<typeof createRandom>): Review[] {
  return Array.from({ length: seed.reviews }, (_, index) => ({
    id: `${seed.id}-review-${index + 1}`,
    author: REVIEW_AUTHORS[(index + seed.tokenNumber) % REVIEW_AUTHORS.length]!,
    rating: seed.id === 'emerald-ape-042' ? 5 : random.chance(0.75) ? 5 : 4,
    comment: REVIEW_COMMENTS[(index * 3 + seed.tokenNumber) % REVIEW_COMMENTS.length]!,
    createdAt: new Date(CATALOG_EPOCH - (index + 1) * 26 * HOUR).toISOString(),
  }))
}

function toFixture(seed: Seed, random: ReturnType<typeof createRandom>): NftFixture {
  const collectionId = seed.collection ?? ART_COLLECTION[seed.art]
  const collectionName = COLLECTIONS[collectionId]
  const creator = CREATORS[seed.creator]!
  const network = NETWORK_LABEL[seed.network]
  const attributes =
    seed.attributes ??
    [
      random.pick(ART_ATTRIBUTES[seed.art]),
      random.pick(ART_ATTRIBUTES[seed.art]),
      random.pick(RARITY),
    ].filter((value, index, list) => list.indexOf(value) === index)

  return {
    id: seed.id,
    tokenId: `#${String(seed.tokenNumber).padStart(4, '0')}`,
    name: seed.name,
    art: seed.art,
    collection: { id: collectionId, name: collectionName },
    creator: { ...creator },
    category: seed.category,
    network: seed.network,
    description: `Um colecionável digital finalizado à mão da coleção ${collectionName}, verificado na ${network}, com arte desbloqueável e acesso para colecionadores.`,
    story: [
      `${seed.name} é uma obra digital finalizada à mão da coleção ${collectionName}. Cada atributo fica armazenado nos metadados do token e verificado na ${network}. A obra explora identidade, movimento e luz em um mundo digital sem fronteiras.`,
      `A propriedade inclui a arte em alta resolução, lançamentos exclusivos para colecionadores e um registro permanente de procedência registrado na rede. ${creator.name} recebe 5% de direitos autorais nas vendas secundárias, apoiando novos trabalhos e lançamentos da comunidade.`,
    ],
    attributes,
    isNew: seed.isNew,
    trendingScore: seed.trendingScore,
    listedAt: seed.listedAt,
    previousPrice: seed.previousPrice ?? null,
    defaultEdition: '1-50',
    editions: buildEditions(seed),
    contract: {
      address: `0x${hexDigest(collectionId, 40)}`,
      standard: seed.network === 'solana' ? 'Metaplex' : 'ERC-721',
      royaltiesBps: 500,
      metadataStorage: 'IPFS',
    },
    reviews: buildReviews(seed, random),
  }
}

export const GENERATED_COUNT = 112

/** Full deterministic catalog: the 8 NFTs drawn in Figma followed by 112 generated ones. */
export function buildCatalog(): NftFixture[] {
  const random = createRandom(42)
  return [...FIGMA_SEEDS, ...generatedSeeds(GENERATED_COUNT)].map((seed) => toFixture(seed, random))
}

