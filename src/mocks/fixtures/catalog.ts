const WIDTHS = [320, 640, 960] as const

function buildImage(art: ArtKey, suffix: string, alt: string): Image {
  const base = `/images/nfts/${art}${suffix}`
  const srcSet = (format: 'avif' | 'webp') =>
    WIDTHS.map((width) => `${base}-${width}.${format} ${width}w`).join(', ')
  return {
    src: `${base}-640.webp`,
    srcSetAvif: srcSet('avif'),
    srcSetWebp: srcSet('webp'),
    width: 640,
    height: 640,
    alt,
    dominantColor: ARTWORK[art].dominantColor,
  }
}

export function mainImage(art: ArtKey, name: string) {
  return buildImage(art, '', `${name}: ${ARTWORK[art].subject}`)
}

export function galleryImages(art: ArtKey, name: string) {
  return GALLERY_VIEWS.map((view, index) =>
    index === 0 ? mainImage(art, name) : buildImage(art, view.suffix, `${name}, ${view.label}`),
  )
}

